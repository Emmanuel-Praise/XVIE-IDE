function pathMatches(name: string, path: string | undefined, segments: string[]): boolean {
  if (!path) return false;
  const normalized = path.replace(/\\/g, "/");
  return segments.some((segment) => normalized.includes(`/${segment}/`));
}

export function fileIconFor(name: string, path?: string): IconSpec {
  const lower = name.toLowerCase();

  const special = SPECIAL_FILENAMES[lower];
  if (special) return special;

  if (pathMatches(name, path, [".github/workflows"]) && /\.(ya?ml)$/.test(lower)) {
    return spec(SiGithubactions, "#2088FF");
  }

  const dot = lower.lastIndexOf(".");
  if (dot > 0 && dot < lower.length - 1) {
    const ext = lower.slice(dot + 1);
    const byExt = EXTENSIONS[ext];
    if (byExt) return byExt;
  }

  return DEFAULT_FILE;
}

export function fileColorFor(name: string, path?: string): string {
  return fileIconFor(name, path).color;
}
